-- MOUAU Election Portal — Supabase (Postgres) schema
-- Run this in Supabase Dashboard → SQL Editor → New query → Paste → Run.

-- ── Candidates ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS candidates (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  level TEXT,
  position TEXT NOT NULL,
  college TEXT,
  dept TEXT,
  votes INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'active',
  matricNo TEXT,
  email TEXT,
  phone TEXT,
  slogan TEXT,
  manifesto TEXT,
  experience TEXT
);

-- ── Students (voter roll) ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS students (
  matricNo TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  level TEXT NOT NULL,
  dept TEXT NOT NULL,
  contactInfo TEXT NOT NULL,
  college TEXT NOT NULL,
  nacomeReceipt TEXT,
  password TEXT NOT NULL,
  registeredAt TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── Votes (one row per voter; matricNo unique = one vote) ────
CREATE TABLE IF NOT EXISTS votes (
  id SERIAL PRIMARY KEY,
  name TEXT,
  matricNo TEXT UNIQUE NOT NULL,
  votedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  manualEntry BOOLEAN NOT NULL DEFAULT FALSE,
  isAutoGenerated BOOLEAN NOT NULL DEFAULT FALSE,
  enteredBy TEXT,
  college TEXT
);

-- ── Vote details (who each voter picked per position) ─────────
CREATE TABLE IF NOT EXISTS vote_details (
  id SERIAL PRIMARY KEY,
  voteId INTEGER NOT NULL REFERENCES votes(id) ON DELETE CASCADE,
  position TEXT NOT NULL,
  candidateName TEXT NOT NULL
);

-- ── Bulk vote audit log ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS bulk_vote_log (
  id SERIAL PRIMARY KEY,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  addedBy TEXT,
  position TEXT,
  candidate TEXT,
  votesAdded INTEGER
);

-- ── Approved matric numbers (registration whitelist) ─────────────
-- Source of truth for registration. backend/data/*.txt files are BACKUP /
-- seed only. Rows: one per (matricNo, level).
CREATE TABLE IF NOT EXISTS approved_matrics (
matricNo TEXT NOT NULL,
level TEXT NOT NULL,
createdAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
PRIMARY KEY (matricNo, level)
);

-- ── System settings (feature flags + deadline) ───────────────
CREATE TABLE IF NOT EXISTS system_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- ── Indexes (same as SQLite version) ─────────────────────────
CREATE INDEX IF NOT EXISTS idx_approved_matrics_matric ON approved_matrics(matricNo);
CREATE INDEX IF NOT EXISTS idx_approved_matrics_level ON approved_matrics(level);
CREATE INDEX IF NOT EXISTS idx_votes_matricNo ON votes(matricNo);
CREATE INDEX IF NOT EXISTS idx_votes_votedAt ON votes(votedAt DESC);
CREATE INDEX IF NOT EXISTS idx_votes_college ON votes(college);
CREATE INDEX IF NOT EXISTS idx_students_matricNo ON students(matricNo);
CREATE INDEX IF NOT EXISTS idx_students_college ON students(college);
CREATE INDEX IF NOT EXISTS idx_students_dept ON students(dept);
CREATE INDEX IF NOT EXISTS idx_students_name ON students(name);
CREATE INDEX IF NOT EXISTS idx_candidates_level ON candidates(level);
CREATE INDEX IF NOT EXISTS idx_candidates_pos ON candidates(position);
CREATE INDEX IF NOT EXISTS idx_votedetails_vote ON vote_details(voteId);

