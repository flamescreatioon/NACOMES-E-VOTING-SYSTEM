/*
 * Neon Postgres adapter with a sqlite3-compatible surface.
 * Exposes: get / all / run / prepare / serialize / close / ready / resetNeon
 * so backend/index.js works unchanged against Neon.
 *
 * Design: a single pg Client + an operation queue. This mirrors SQLite's
 * serialized execution, which matters because index.js issues
 * BEGIN TRANSACTION ... COMMIT across separate run() calls — those must
 * hit the same connection in order. A pool would scatter them.
 *
 * Notes:
 * - `?` placeholders are rewritten to $1, $2, ... per statement.
 * - INSERT OR IGNORE  -> ON CONFLICT DO NOTHING (+ RETURNING id for votes).
 * - INSERT OR REPLACE -> ON CONFLICT(key) DO UPDATE.
 * - run() callback `this` provides { lastID, changes } like sqlite3.
 * - prepare() returns { run(params..., cb), finalize(cb) }.
 * - serialize() runs the function immediately (queue handles ordering).
 */
