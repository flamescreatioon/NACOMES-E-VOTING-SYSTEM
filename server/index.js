// Bulk Admin Vote
app.post('/api/vote/bulk', (req, res) => {
    const { position, candidate, voteCount, addedBy } = req.body;
    
    if (!position || !candidate || !voteCount) {
        return res.status(400).json({ error: "Missing parameters" });
    }

    db.serialize(() => {
        db.run("BEGIN TRANSACTION");

        // Update candidate absolute count directly for performance
        db.run("UPDATE candidates SET votes = votes + ? WHERE position = ? AND name = ?", [voteCount, position, candidate]);
        
        // Log bulk action
        db.run("INSERT INTO bulk_vote_log (addedBy, position, candidate, votesAdded) VALUES (?, ?, ?, ?)", [addedBy, position, candidate, voteCount]);
        
        // Generate fake voters to match ledger
        const fakeFirstNames = ["John", "Jane", "Michael", "Sarah", "David", "Grace", "Samuel", "Ngozi", "Emeka", "Amina", "Chinedu", "Fatima", "Yusuf", "Jennifer", "Ibrahim", "Daniel", "Joy", "Victor", "Blessing", "Emmanuel"];
        const fakeLastNames = ["Okonkwo", "Eze", "Johnson", "Obi", "Nduka", "Okoli", "Ade", "Nwankwo", "Bello", "Peters", "Chukwu", "Abdullahi", "Olu", "Kalu", "Ojo", "Idris"];
        
        const stmtVote = db.prepare("INSERT INTO votes (name, matricNo, isAutoGenerated, enteredBy) VALUES (?, ?, 1, ?)");
        const stmtDetails = db.prepare("INSERT INTO vote_details (voteId, position, candidateName) VALUES (?, ?, ?)");
        
        let pending = voteCount;
        for (let i = 0; i < voteCount; i++) {
            const firstName = fakeFirstNames[Math.floor(Math.random() * fakeFirstNames.length)];
            const lastName = fakeLastNames[Math.floor(Math.random() * fakeLastNames.length)];
            const year = 2020 + Math.floor(Math.random() * 5);
            const idStr = Math.floor(100000 + Math.random() * 900000);
            
            stmtVote.run(`${firstName} ${lastName}`, `U${year}/${idStr}`, addedBy, function(err) {
                if (!err) {
                    stmtDetails.run(this.lastID, position, candidate);
                }
                pending--;
                if (pending === 0) {
                    stmtVote.finalize();
                    stmtDetails.finalize();
                    db.run("COMMIT");
                    res.json({ success: true, message: `Added ${voteCount} votes to ${candidate}` });
                }
            });
        }
    });
});

